"""
Module 2: Fine-Tuning
======================
Adapt a pre-trained model to specific tasks or domains by retraining
on targeted datasets for higher accuracy and relevance.

This module demonstrates LoRA (Low-Rank Adaptation) fine-tuning — the
industry-standard parameter-efficient technique that:
  • Injects small trainable rank-decomposition matrices into the model
  • Freezes the original weights (only ~0.1% of params are trained)
  • Produces a task-specific adapter that can be merged or swapped

Here we fine-tune DistilGPT-2 (82 M params) on a small synthetic
dataset of radio-style news intros to show the before/after shift
in generation style.  The same LoRA config translates directly to
larger models (LLaMA, Mistral, etc.) — only the base_model changes.

Run standalone
--------------
  python -m modules.m2_fine_tune

Requirements (separate from the core POC)
------------------------------------------
  pip install transformers torch peft datasets accelerate
"""

