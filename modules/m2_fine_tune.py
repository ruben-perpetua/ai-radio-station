def create_dataset_file(output_path: str = "data/finetune_dataset.jsonl") -> str:
    """Persist the training examples to disk in JSONL format."""
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        for example in TRAINING_EXAMPLES:
            f.write(json.dumps({"text": example}) + "\n")
    print(f"  ✓ Dataset saved: {out} ({len(TRAINING_EXAMPLES)} examples)")
    return str(out)


def run_finetune_demo(
    base_model: str = "distilgpt2",
    output_dir: str = "output/finetuned_model",
    num_train_steps: int = 30,
) -> None:
    """
    Fine-tune `base_model` using LoRA (PEFT) on the radio-style dataset.
    Prints before/after generation samples to show the style shift.

    Parameters
    ----------
    base_model       : HuggingFace model ID or local path
    output_dir       : where to save the fine-tuned adapter weights
    num_train_steps  : training steps — 30 is enough to see style shift on CPU
    """
    # ── Lazy imports (optional deps) ─────────────────────────────────────────
    try:
        import torch
        from datasets import Dataset
        from peft import LoraConfig, TaskType, get_peft_model
        from transformers import (
            AutoModelForCausalLM,
            AutoTokenizer,
            DataCollatorForLanguageModeling,
            Trainer,
            TrainingArguments,
        )
    except ImportError:
        print(
            "\n  ⚠  Fine-tuning dependencies not installed.\n"
            "     Run: pip install transformers torch peft datasets accelerate\n"
        )
        return

    print(f"\n{'='*60}")
    print("  MODULE 2: LoRA Fine-Tuning Demo")
    print(f"{'='*60}")
    print(f"  Base model      : {base_model}")
    print(f"  Training steps  : {num_train_steps}")
    print(f"  Dataset size    : {len(TRAINING_EXAMPLES)} radio-style examples")
    print(f"  Technique       : LoRA (Low-Rank Adaptation via PEFT)")
    print()

    # ── Load tokeniser and model ──────────────────────────────────────────────
    print("  Loading tokeniser and base model...")
    tokenizer = AutoTokenizer.from_pretrained(base_model)
    tokenizer.pad_token = tokenizer.eos_token

    base = AutoModelForCausalLM.from_pretrained(base_model)
    base.config.pad_token_id = tokenizer.eos_token_id

    # ── Before fine-tuning ────────────────────────────────────────────────────
    test_prompt = "Welcome to AI Tech Radio! Today's top story:"
    print("\n  ── BEFORE fine-tuning ──────────────────────────────────────")
    before_text = _generate(base, tokenizer, test_prompt, max_new_tokens=60)
    print(textwrap.fill(f"  {before_text}", width=70, subsequent_indent="  "))

    # ── LoRA configuration ────────────────────────────────────────────────────
    lora_config = LoraConfig(
        task_type=TaskType.CAUSAL_LM,
        r=8,               # rank — small rank = fewer trainable params
        lora_alpha=16,     # scaling factor
        lora_dropout=0.1,
        target_modules=["c_attn"],   # GPT-2 attention projection
        bias="none",
    )
    model = get_peft_model(base, lora_config)

    trainable, total = model.get_nb_trainable_parameters()
    print(f"\n  LoRA trainable params : {trainable:,}  ({100*trainable/total:.2f}% of total)")

    # ── Dataset ───────────────────────────────────────────────────────────────
    raw_dataset = Dataset.from_list([{"text": t} for t in TRAINING_EXAMPLES])

    def tokenize(batch):
        return tokenizer(
            batch["text"],
            truncation=True,
            max_length=128,
            padding="max_length",
        )

    tokenized = raw_dataset.map(tokenize, batched=True, remove_columns=["text"])

    # ── Training ──────────────────────────────────────────────────────────────
    args = TrainingArguments(
        output_dir=output_dir,
        num_train_epochs=max(1, num_train_steps // len(TRAINING_EXAMPLES) + 1),
        max_steps=num_train_steps,
        per_device_train_batch_size=2,
        learning_rate=3e-4,
        logging_steps=10,
        save_strategy="no",
        report_to="none",
        no_cuda=not torch.cuda.is_available(),
    )

    trainer = Trainer(
        model=model,
        args=args,
        train_dataset=tokenized,
        data_collator=DataCollatorForLanguageModeling(tokenizer, mlm=False),
    )

    print(f"\n  Training for {num_train_steps} steps...")
    trainer.train()
    print("  Training complete.")

    # ── After fine-tuning ─────────────────────────────────────────────────────
    print("\n  ── AFTER fine-tuning ───────────────────────────────────────")
    after_text = _generate(model, tokenizer, test_prompt, max_new_tokens=60)
    print(textwrap.fill(f"  {after_text}", width=70, subsequent_indent="  "))

    # ── Save adapter ──────────────────────────────────────────────────────────
    os.makedirs(output_dir, exist_ok=True)
    model.save_pretrained(output_dir)
    tokenizer.save_pretrained(output_dir)
    print(f"\n  ✓ LoRA adapter saved to: {output_dir}")
    print(f"  ✓ Load later: model = AutoModelForCausalLM.from_pretrained('{output_dir}')")


def _generate(model, tokenizer, prompt: str, max_new_tokens: int = 60) -> str:
    import torch
    inputs = tokenizer(prompt, return_tensors="pt")
    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=True,
            temperature=0.7,
            pad_token_id=tokenizer.eos_token_id,
        )
    return tokenizer.decode(out[0], skip_special_tokens=True)


